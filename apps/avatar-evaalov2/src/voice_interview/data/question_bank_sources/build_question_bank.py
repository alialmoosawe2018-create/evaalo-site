def _normalize_title_key(title: str) -> str:
    s = (title or "").strip().lower()
    s = re.sub(r"[\s_/]+", " ", s)
    s = re.sub(r"[^a-z0-9\u0600-\u06ff ]", "", s)
    return re.sub(r"\s+", " ", s).strip()


def _load_slug_aliases_from_existing() -> dict[str, str]:
    """Preserve slug aliases when position_catalog no longer ships SLUG_ALIASES."""
    if SLUG_ALIASES:
        return dict(SLUG_ALIASES)
    if not OUT_PATH.is_file():
        return {}
    try:
        raw = json.loads(OUT_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    reg = raw.get("position_registry") or {}
    out: dict[str, str] = {}
    for slug, entry in reg.items():
        if isinstance(entry, dict):
            canonical = entry.get("alias_of")
            if isinstance(canonical, str) and canonical.strip():
                out[str(slug)] = canonical.strip()
    return out


def _load_title_aliases_from_existing() -> dict[str, str]:
    if TITLE_ALIASES:
        return dict(TITLE_ALIASES)
    if not OUT_PATH.is_file():
        return {}
    try:
        raw = json.loads(OUT_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    title_index = raw.get("title_index") or {}
    rows_by_slug = {slug_from_position_label(t): t for t, _, _ in POSITION_ROWS}
    out: dict[str, str] = {}
    for phrase, slug in title_index.items():
        if not isinstance(phrase, str) or not isinstance(slug, str):
            continue
        canonical_title = rows_by_slug.get(slug)
        if not canonical_title:
            continue
        norm_phrase = _normalize_title_key(phrase)
        norm_canonical = _normalize_title_key(canonical_title)
        if norm_phrase and norm_phrase != norm_canonical:
            out[phrase] = canonical_title
    return out


def build_position_registry() -> dict[str, dict[str, str]]:
    registry: dict[str, dict[str, str]] = {}
    title_index: dict[str, str] = {}
    for title, category, industry_family in POSITION_ROWS:
        slug = slug_from_position_label(title)
        if not slug:
            continue
        if category not in CATEGORIES:
            print(f"  WARN unknown category {category!r} for {title!r}")
        if industry_family not in INDUSTRY_FAMILIES:
            print(f"  WARN unknown industry_family {industry_family!r} for {title!r}")
        registry[slug] = {
            "title": title,
            "category": category,
            "industry_family": industry_family,
        }
        title_index[_normalize_title_key(title)] = slug
    slug_aliases = _load_slug_aliases_from_existing()
    title_aliases = _load_title_aliases_from_existing()
    for alias_slug, canonical in slug_aliases.items():
        if canonical in registry:
            registry[alias_slug] = {**registry[canonical], "alias_of": canonical}
        else:
            print(f"  WARN slug alias target missing: {alias_slug!r} -> {canonical!r}")
    title_to_slug = {
        _normalize_title_key(t): slug_from_position_label(t) for t, _, _ in POSITION_ROWS
    }
    for alias_phrase, canonical_title in title_aliases.items():
        canonical_slug = title_to_slug.get(_normalize_title_key(canonical_title))
        if not canonical_slug or canonical_slug not in registry:
            print(f"  WARN title alias target missing: {alias_phrase!r} -> {canonical_title!r}")
            continue
        title_index[_normalize_title_key(alias_phrase)] = canonical_slug
    registry["__title_index__"] = title_index  # type: ignore[assignment]
    return registry


def build_jobs(registry: dict[str, dict[str, str]]) -> dict[str, list[str]]:
    """jobs[slug] = CATEGORIES[category]; skip alias_of slugs (dedupe)."""
    jobs: dict[str, list[str]] = {}
    for slug, entry in registry.items():
        if not isinstance(entry, dict) or "title" not in entry:
            continue
        if "alias_of" in entry:
            continue
        category = entry.get("category", "")
        bank = CATEGORIES.get(category)
        if not bank:
            print(f"  WARN no category bank for {slug!r} (category={category!r})")
            continue
        jobs[slug] = list(bank)
    return jobs


def main() -> None:
    registry = build_position_registry()
    title_index = registry.pop("__title_index__", {})
    jobs = build_jobs(registry)

    payload = {
        "jobs": jobs,
        "categories": CATEGORIES,
        "industry_families": INDUSTRY_FAMILIES,
        "position_registry": {
            k: v for k, v in registry.items() if isinstance(v, dict) and "title" in v
        },
        "title_index": title_index,
        "__default__": DEFAULT_ANCHORS,
    }

    OUT_PATH.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(
        f"Wrote {OUT_PATH} | jobs={len(jobs)} "
        f"positions={len(payload['position_registry'])} "
        f"categories={len(CATEGORIES)} families={len(INDUSTRY_FAMILIES)} "
        f"title_index={len(title_index)}"
    )
