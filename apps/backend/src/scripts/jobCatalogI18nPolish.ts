export function polishTranslation(text: string, lang: Lang, baseDict: Record<string, string>): string {
    if (!text || !hasEnglishRemnants(text)) return text;

    const polish = lang === 'ar' ? POLISH_AR : POLISH_KU;
    const combined = { ...baseDict, ...polish };
    let result = text;

    for (let pass = 0; pass < 4 && hasEnglishRemnants(result); pass++) {
        const keys = Object.keys(combined)
            .filter((k) => /[A-Za-z]/.test(k))
            .sort((a, b) => b.length - a.length);

        for (const key of keys) {
            if (result.includes(key)) {
                result = result.split(key).join(combined[key]);
            }
        }

        LATIN_WORD_RE.lastIndex = 0;
        result = result.replace(LATIN_WORD_RE, (word) => combined[word] ?? word);
    }

    return result.replace(/\s+/g, ' ').trim();
}
