const LATIN_WORD_RE = /[A-Za-z][A-Za-z0-9&/\-]*/g;

export function hasEnglishRemnants(value: string): boolean {
    LATIN_WORD_RE.lastIndex = 0;
    return LATIN_WORD_RE.test(value);
}

