function phraseDict(lang: Lang): Record<string, string> {
    const base = lang === 'ar' ? PHRASES_AR : PHRASES_KU;
    const extra = lang === 'ar' ? EXTRA_PHRASES_AR : EXTRA_PHRASES_KU;
    return { ...base, ...extra };
}

function translatePhraseChunk(text: string, lang: Lang): string {
    const dict = phraseDict(lang);
    const phrases = Object.keys(dict).sort((a, b) => b.length - a.length);
    let remaining = text.trim();
    if (!remaining) return remaining;
    if (dict[remaining]) return dict[remaining];

    const parts: string[] = [];
    while (remaining.length > 0) {
        let matched = false;
        for (const phrase of phrases) {
            if (remaining === phrase || remaining.startsWith(`${phrase} `) || remaining.endsWith(` ${phrase}`) || remaining.includes(` ${phrase} `)) {
                const idx = remaining.indexOf(phrase);
                if (idx > 0) parts.push(translatePhraseChunk(remaining.slice(0, idx).trim(), lang));
                parts.push(dict[phrase]);
                remaining = remaining.slice(idx + phrase.length).trim();
                matched = true;
                break;
            }
        }
        if (!matched) {
            const word = remaining.split(/\s+/)[0];
            parts.push(dict[word] || word);
            remaining = remaining.slice(word.length).trim();
        }
    }
    return parts.filter(Boolean).join(' ').replace(/\s+/g, ' ').trim();
}

function finalizeTranslation(title: string, lang: Lang, memory: Map<string, string>, raw: string): string {
    const polished = polishTranslation(raw, lang, phraseDict(lang));
    memory.set(`${lang}:${title}`, polished);
    return polished;
}

export function translateDisplayTitle(
    title: string,
    lang: Lang,
    memory: Map<string, string>
): string {
    const cached = memory.get(`${lang}:${title}`);
    if (cached) return cached;

    for (const rule of RULES) {
        const m = title.match(rule.re);
        if (m) {
            const tr = (s: string) => translateDisplayTitle(s, lang, memory);
            const result = rule.build(m, tr, lang);
            return finalizeTranslation(title, lang, memory, result);
        }
    }

    const viaPhrase = translatePhraseChunk(title, lang);
    return finalizeTranslation(title, lang, memory, viaPhrase);
}

export function seedMemoryFromLabels(
    labels: Record<string, string>,
    lang: Lang
): Map<string, string> {
    const memory = new Map<string, string>();
    for (const [key, value] of Object.entries(labels)) {
        if (!isTranslated(value, lang) || hasEnglishRemnants(value)) continue;
        memory.set(`${lang}:${key}`, value);
        if (!key.includes('.')) memory.set(`${lang}:${key}`, value);
    }
    return memory;
}

export function buildEnMemory(labels: Record<string, string>, lang: Lang): Map<string, string> {
    const memory = seedMemoryFromLabels(labels, lang);
    for (const [key, value] of Object.entries(labels)) {
        if (!isTranslated(value, lang) || hasEnglishRemnants(value)) continue;
        if (!key.includes('.')) {
            memory.set(`${lang}:${key}`, value);
        }
        if (key.includes('.')) {
            memory.set(`${lang}:${key}`, value);
        }
    }
    return memory;
}
