const ARABIC_RE = /[\u0600-\u06FF]/;
const KURDISH_RE = /[\u0600-\u06FF\u0750-\u077F]/;

export function isTranslated(value: string, lang: Lang): boolean {
    if (!value) return false;
    return lang === 'ar' ? ARABIC_RE.test(value) : KURDISH_RE.test(value) && !/^[\x00-\x7F]+$/.test(value);
}

