/**
 * مفتاح مطابقة من رقم الهاتف.
 *
 * الحاجة إليه من ملاحظة صاحب المنتج (2026-09-08): حارس التكرار على التقديم العامّ
 * يطابق **البريد وحده**، فإعادة التقديم لنفس الحملة ببريدٍ آخر تُنشئ شخصاً جديداً
 * وتقديماً جديداً — وبالتالي رابط مقابلة نظيفاً. والهاتف مُعرِّفٌ أقوى من البريد
 * في العراق، والنموذج يجمعه أصلاً ولا يُستعمل في المطابقة إطلاقاً.
 *
 * ⚠️ والتطبيع ليس تفصيلاً: صيغ الأرقام في قاعدة الإنتاج متضاربة فعلاً — ‎`+964…`،
 * و‎`0…`، و‎`+964` متبوعاً بصفرٍ زائد، ومسافات، وحتى `(783) 309-9675`. مقارنةُ النصّ
 * كما هو تفشل صامتةً على كلّ واحدة منها.
 *
 * ولماذا بادئة `IQ:`/`INTL:` بدل الأرقام وحدها: في البيانات رقمٌ يمنيّ
 * (‎`+967 778971562`). لو جُرِّدت رموز الدول لأصبح مطابقاً لرقمٍ عراقيّ محليّ
 * ‎`0778971562` — أي منعُ مرشّحٍ بريء بسبب تشابهٍ وهميّ. البادئة تُبقيهما منفصلين.
 *
 * حدٌّ معروف ومقبول: رقمٌ أجنبيّ يُكتب بصيغة محليّة (‎`0…`) يُقرأ عراقيّاً. لا سبيل
 * لتمييزه بلا سياق بلد، وهو أندر بكثير من الحالة التي نعالجها.
 */
export function normalizePhoneKey(raw?: string | null): string {
    const digits = String(raw ?? '').replace(/\D/g, '');
    if (!digits) return '';

    // بادئة الاتصال الدولي
    const noIdd = digits.startsWith('00') ? digits.slice(2) : digits;
    if (!noIdd) return '';

    // العراق برمز الدولة — مع صفرٍ زائد أحياناً بعده (‎+96407734045591)
    if (noIdd.startsWith('964')) {
        const national = noIdd.slice(3).replace(/^0+/, '');
        return national ? `IQ:${national}` : '';
    }

    // صيغة محليّة: صفر ثم الرقم الوطني
    if (noIdd.startsWith('0')) {
        const national = noIdd.replace(/^0+/, '');
        return national ? `IQ:${national}` : '';
    }

    // جوّال عراقيّ مكتوب بلا صفر ولا رمز دولة (‎7XXXXXXXXX)
    if (noIdd.length === 10 && noIdd.startsWith('7')) return `IQ:${noIdd}`;

    // غير ذلك: رقم أجنبيّ يبقى بهويّته الدولية كاملة
    return `INTL:${noIdd}`;
}

/** هل يشير الرقمان إلى نفس المشترك بعد التطبيع؟ فارغٌ لا يطابق فارغاً. */
export function isSamePhone(a?: string | null, b?: string | null): boolean {
    const ka = normalizePhoneKey(a);
    const kb = normalizePhoneKey(b);
    return Boolean(ka) && ka === kb;
}
