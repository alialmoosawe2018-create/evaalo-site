/**
 * من أنهى الجلسة الصوتية — وهل كانت تلك النهاية «انتهاء المقابلة» فعلاً.
 *
 * السبب: في 2026-09-09 ضغط مرشّح زرّ End بعد أربع إجابات، فاستُهلك رابطه في
 * نفس المِلّي ثانية، وحين أعاد الفتح بعد ثماني ثوانٍ رُفض بـ4001. الثواني
 * الثماني هي الدليل أنّه لم يقصد الإنهاء. وقياساً على السجلّات المحفوظة:
 * خمس عشرة جلسة، واحدة فقط أغلقها الخادم — أي أنّ أربع عشرة جلسة عوملت
 * معاملة «مقابلة مكتملة» بينما لم يُنهِها الخادم أصلاً.
 *
 * الخادم يعرف الفرق دائماً — هو من يستدعي ws.close — فلا حاجة لأي تغيير في
 * البروتوكول: يكفي أن نسجّل السبب عند كل موضع إغلاق ونقرأه في معالج close.
 */
export type VoiceSessionEndCause =
  /** أغلق المتصفّح: زرّ End، أو إغلاق التبويب، أو انقطاع الشبكة. لا نعرف أيّها. */
  | "client"
  /** المقابلة بلغت نهايتها المصمَّمة (خاتمة طبيعية أو انتهاء الوقت المخصّص). */
  | "interview_complete"
  /** استُنفد السقف الزمني الصلب للجلسة. */
  | "max_duration"
  /** صمتٌ طويل: الخادم أغلق جلسة خاملة. */
  | "idle_timeout"
  /** نفدت الأرصدة أثناء المقابلة فقُصّت الجلسة — ليست نهاية المرشّح. */
  | "credits_exhausted"
  /** رُفضت الجلسة قبل أن تبدأ (فوترة، سعة، إعداد، رسالة أكبر من الحدّ). */
  | "server_refused"
  /** الرابط كان مستهلكاً أصلاً. */
  | "link_consumed";

/**
 * هل تُعدّ هذه النهاية «مقابلةً جرت حتى آخرها»؟
 *
 * وحدها هذه الحالات تُقفل الرابط. ما عداها يُبقيه صالحاً — فالكلفة غير
 * متماثلة: إبقاء رابطٍ مفتوحاً لمن أنهى فعلاً يعني محاولة زائدة، بينما قفله
 * على من انقطع يعني حرمانه من المقابلة كلّها بلا طريق رجوع.
 *
 * `idle_timeout` خارج القائمة عمداً: الصمت الطويل قد يكون ميكروفوناً تعطّل.
 * و`credits_exhausted` كذلك — تلك نهايةٌ سبّبناها نحن لا هو.
 */
export function completesInterview(cause: VoiceSessionEndCause): boolean {
  return cause === "interview_complete" || cause === "max_duration";
}

/**
 * هل يجب أن يُبلَّغ التقييم «غير مكتملة» بدل رقمٍ ورفض؟
 *
 * مقابلة تنتهي قبل المرحلة الثالثة تخسر خمس عشرة نقطة من مئة بحكم الشيفرة
 * وحدها (`phase < 3` ⇒ englishFluency = 0)، فسقفها الواقعيّ ستّون ورقمها غير
 * قابل للمقارنة بمن أكمل. الإبلاغ عنها كرقم رفض يمنح مدير التوظيف ثقةً
 * كاذبة؛ والإبلاغ عنها كـ«غير مكتملة» يقول الحقيقة.
 *
 * الشرطان معاً: أن يكون المتصفّح هو من أغلق، وأن تكون المرحلة دون الثالثة.
 * فمن وصل المرحلة الثالثة ثمّ أغلق بعد آخر إجابة قد أعطى ما يكفي.
 */
export function endedBeforeEnglishPhase(opts: {
  completedByServer: boolean;
  phaseReached?: number | null;
}): boolean {
  if (opts.completedByServer) return false;
  // ⚠️ لا تكتب Number(opts.phaseReached) مباشرة: Number(null) تساوي صفراً وهي
  // عددٌ نهائيّ، فتمرّ «مرحلة مجهولة» بوصفها المرحلة صفر ويُقلب تقرير المرشّح
  // إلى «غير مكتملة» بلا دليل. غياب المعلومة ليس معلومة.
  if (opts.phaseReached === null || opts.phaseReached === undefined) return false;
  const phase = Number(opts.phaseReached);
  if (!Number.isFinite(phase)) return false;
  return phase < 3;
}

/** ما يُرفق بالحمولة الصادرة إلى n8n كي يقرّر المقيّم على أساسه. */
export interface VoiceSessionEndSummary {
  cause: VoiceSessionEndCause;
  completedByServer: boolean;
  /** رمز إغلاق WebSocket كما وصل — 1000 عادي، 1006 انقطاع غير طبيعي. */
  closeCode?: number;
  closeReason?: string;
  phaseReached?: number | null;
  /** صحيحة ⇒ يُبلَّغ التقييم «غير مكتملة» بدل رقم. */
  earlyEnd: boolean;
}
